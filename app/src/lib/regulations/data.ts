/** Адрес-якорь пункта на странице `/rules`: `4.3` → `p-4-3`. */
export function itemAnchor(num: string): string {
  return `p-${num.replace(/\./g, '-')}`
}

/** Ссылка на пункт: `/rules#p-4-3`. */
export function itemHref(num: string): string {
  return `/rules#${itemAnchor(num)}`
}

const BY_NUM = new Map(REG_ITEMS.map((item) => [item.num, item]))

/** Пункт по номеру или `undefined`. */
export function findItem(num: string): RegItem | undefined {
  return BY_NUM.get(num)
}

/** Пункты одного раздела по порядку. */
export function itemsOfSection(sectionId: string): RegItem[] {
  return REG_ITEMS.filter((item) => item.section === sectionId)
}
