// Признак «человеку сейчас тяжело» в тексте вопроса помощнику (20.11, «Поддержка»). Чистая функция: без базы, без сети, без модели.
// Решение, которое она несёт: при совпадении модель не вызывается, поиск по положению не показывается, вопрос нигде не сохраняется.
//
// Выбор между пропуском и ложным срабатыванием: пропуск тяжелее. Поэтому признаки широкие там, где слово почти однозначно
// («суицид», «самоповрежд», «хочу умереть»), и узкие там, где у слова есть бытовой смысл:
//  - «покончить» считается только в связке «с собой / с жизнью / со всем»: «покончить с долгами» — не признак;
//  - «не хочу жить» не считается, если дальше названо место или сосед: «не хочу жить в общежитии» — вопрос про общежитие;
//  - «нет смысла» считается только вместе с «жить» или «в жизни»: «нет смысла сдавать реферат» — не признак;
//  - «хочу умереть со смеху» — не признак.
// Ложное срабатывание стоит одной карточки с номерами; список ниже — в тесте `tests/unit/support-crisis.test.ts`.

const MAX_LENGTH = 2000

/** Нижний регистр, «ё» → «е», всё, кроме букв и цифр, — пробел, повторы пробелов схлопнуты. Невидимые знаки не склеивают слова. */
export function normalizeForCrisis(text: string): string {
  return text
    .slice(0, MAX_LENGTH)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[​-‏⁠﻿­]/g, '')
    .replace(/[^a-zа-я0-9]+/g, ' ')
    .trim()
}

// Слово начинается здесь: перед ним не буква. `\b` с кириллицей не работает, поэтому границы заданы явно.
const START = '(?<![а-я])'
const END = '(?![а-я])'
// Слова-вставки между «не хочу» и «жить»: «не хочу больше жить», «не хочу так жить».
const FILLER = '(?: (?:больше|уже|так|совсем|вообще|дальше|тут|здесь))*'
// После «жить» названо место или сосед: «не хочу жить в общежитии», «не хочу жить с соседом» — вопрос про быт.
// «Не хочу жить в этом мире» сюда не попадает: там названо не место проживания.
const PLACE = '(?:общежити|общаг|комнат|квартир|москв|город|дом|кампус|студгородк|корпус|сосед|родител|мам|пап|друз|подруг)'
const LIVE_ELSEWHERE = `(?! (?:в|на|у|с|со|около|возле|рядом с|вместе с|отдельно от) ${PLACE})(?! (?:отдельно|вместе|далеко)${END})`

const PATTERNS: readonly RegExp[] = [
  // «не хочу жить», «не хочется больше жить», «жить не хочу»
  new RegExp(`${START}не (?:хочу|хочет|хочется|хотел|хотела|хотим)${FILLER} жить${END}${LIVE_ELSEWHERE}`),
  new RegExp(`${START}жить (?:больше |уже |совсем )?не (?:хочу|хочет|хочется|хотел|хотела)${END}`),
  new RegExp(`${START}(?:надоело|устал|устала|устали) жить${END}${LIVE_ELSEWHERE}`),
  // «нет смысла жить», «не вижу смысла в жизни», «жить незачем»
  new RegExp(`${START}(?:нет|не вижу|не вижу больше|не осталось) смысла (?:больше )?(?:жить|в жизни|существовать)${END}`),
  new RegExp(`${START}(?:жить незачем|незачем жить|смысла жить нет)${END}`),
  new RegExp(`${START}жизнь (?:бессмысленна|не имеет смысла|потеряла смысл)${END}`),
  // «всё бессмысленно» (после нормализации «все бессмысленно»), «ничто не имеет смысла»
  new RegExp(`${START}все(?: это| вокруг)? (?:стало )?бессмысленно${END}`),
  new RegExp(`${START}(?:ничто|ничего|все) не имеет смысла${END}`),
  new RegExp(`${START}все потеряло смысл${END}`),
  // «хочу умереть», «лучше бы умереть»
  new RegExp(`${START}(?:хочу|хочется|хочет|хотелось бы|хотела бы|хотел бы) (?:бы )?(?:умереть|умирать|сдохнуть|не жить|не проснуться)${END}(?! (?:со смеху|от смеха|от скуки|от усталости))`),
  new RegExp(`${START}лучше (?:бы )?(?:умереть|я умер|я умерла|не жить|не родиться|мне умереть)`),
  // «покончить с собой / с жизнью / со всем»
  new RegExp(`${START}(?:покончить|покончу|покончил|покончила|покончим) (?:с собой|с жизнью|со всем этим|со всем|жизнь самоубийством)`),
  new RegExp(`${START}(?:лишить|лишу|лишил|лишила) себя жизни`),
  new RegExp(`${START}(?:свести|сведу|свела) счеты с жизнью`),
  new RegExp(`${START}наложить на себя руки`),
  // «убить себя»
  new RegExp(`${START}(?:убить|убью|убил|убила|убиваю|убивать) себя${END}`),
  // «суицид», «самоубийство», «суицидальные мысли»
  new RegExp(`${START}(?:суицид|самоубийств|самоубиться|суицидальн)`),
  // «самоповреждение», «навредить себе», «режу себя», «вскрыть вены»
  new RegExp(`${START}(?:самоповрежд|самоповрежден|самоистяз|селфхарм|self harm|selfharm)`),
  new RegExp(`${START}(?:навредить|причинить вред|причинять вред|сделать больно) себе${END}`),
  new RegExp(`${START}(?:режу|резать|порезать|порежу|порезал|порезала) себя${END}`),
  new RegExp(`${START}(?:вскрыть|вскрою|вскрыл|вскрыла|резать) вены${END}`),
  // способы: «повеситься», «спрыгнуть с крыши»
  new RegExp(`${START}(?:повеситься|повешусь|повесился|повесилась)${END}`),
  new RegExp(`${START}(?:спрыгнуть|прыгнуть|шагнуть|броситься|выброситься) (?:с крыши|с моста|из окна|под поезд)`),
]

/**
 * Похож ли текст на сообщение человека, которому сейчас тяжело. Не строка и пустая строка — нет.
 * Регистр и «ё» не важны; знаки препинания — как пробелы. Длинный текст проверяется по первым 2000 знакам.
 */
export function isCrisisText(text: unknown): boolean {
  if (typeof text !== 'string' || text.length === 0) return false
  const normalized = normalizeForCrisis(text)
  if (normalized === '') return false
  return PATTERNS.some((pattern) => pattern.test(normalized))
}
